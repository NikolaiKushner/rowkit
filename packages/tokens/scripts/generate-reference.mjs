/**
 * Generates `src/reference.data.ts`: what every token a theme may set is for.
 *
 * The descriptions are the JSDoc comments beside the values in `color.ts`,
 * `size.ts`, `style.ts`, `shadow.ts`, `radius.ts` and `typography.ts` — written
 * once, where the value is, and read by an editor's hover as well as by this
 * script. The docs site's Tokens page, the package's AGENTS.md and anyone who
 * imports `@rowkit/tokens/reference` read the result.
 *
 * Run `pnpm --filter @rowkit/tokens docs:reference` after changing a token;
 * `src/reference.test.ts` fails when a token has no comment or the committed
 * file has drifted from the source.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'
import ts from 'typescript'

const src = fileURLToPath(new URL('../src/', import.meta.url))
const out = fileURLToPath(new URL('../src/reference.data.ts', import.meta.url))

/** Where each themable scale is written, and the variable prefix a theme sets it by. */
export const sources = [
  { file: 'color.ts', object: 'semanticColor', prefix: '--color-', group: 'color' },
  { file: 'shadow.ts', object: 'shadow', prefix: '--rk-shadow-', group: 'shadow' },
  { file: 'size.ts', object: 'size', prefix: '--spacing-', group: 'size' },
  { file: 'radius.ts', object: 'radiusFactor', prefix: '--radius-', group: 'radius' },
  { file: 'radius.ts', object: 'radius', prefix: '--radius-', group: 'radius' },
  { file: 'style.ts', object: 'style', prefix: '--rk-', group: 'style' },
  { file: 'typography.ts', object: 'fontFamily', prefix: '--font-', group: 'font' },
  { file: 'typography.ts', object: 'fontSize', prefix: '--text-', group: 'font' },
  { file: 'typography.ts', object: 'fontWeight', prefix: '--font-weight-', group: 'font' },
]

/** A JSDoc comment as one line: its first paragraph, tags dropped. */
function summary(node) {
  const doc = ts.getJSDocCommentsAndTags(node).find((d) => ts.isJSDoc(d))
  const text =
    typeof doc?.comment === 'string' ? doc.comment : (ts.getTextOfJSDocComment(doc?.comment) ?? '')
  return text
    .split(/\n\s*\n/)[0]
    .replace(/\s+/g, ' ')
    .trim()
}

function objectLiteral(sourceFile, name) {
  let found
  sourceFile.forEachChild((node) => {
    if (!ts.isVariableStatement(node)) return
    for (const decl of node.declarationList.declarations) {
      if (decl.name.getText(sourceFile) !== name || !decl.initializer) continue
      let init = decl.initializer
      while (ts.isAsExpression(init) || ts.isSatisfiesExpression(init)) init = init.expression
      if (ts.isObjectLiteralExpression(init)) found = init
    }
  })
  if (!found)
    throw new Error(`generate-reference: no object literal ${name} in ${sourceFile.fileName}`)
  return found
}

/** Every token name a source declares, with its comment — empty where it has none. */
export async function readDescriptions() {
  const descriptions = {}
  for (const { file, object, prefix, group } of sources) {
    const text = await readFile(src + file, 'utf8')
    const sourceFile = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true)
    /*
     * A run of tokens with no blank line between them shares the comment above
     * its first: `control-xs` … `control-lg` under «Control heights». A token
     * whose role differs from its run's carries a comment of its own.
     */
    let shared = ''
    let lastLine = -2
    for (const prop of objectLiteral(sourceFile, object).properties) {
      if (!ts.isPropertyAssignment(prop)) continue
      const key = prop.name.getText(sourceFile).replace(/^['"]|['"]$/g, '')
      const own = summary(prop)
      const startLine = sourceFile.getLineAndCharacterOfPosition(
        prop.getStart(sourceFile, true)
      ).line
      const blankBefore = startLine - lastLine > 1
      shared = own || (blankBefore ? '' : shared)
      lastLine = sourceFile.getLineAndCharacterOfPosition(prop.getEnd()).line
      descriptions[`${prefix}${key}`] = { group, description: shared }
    }
  }
  return descriptions
}

export async function buildReferenceData() {
  const descriptions = await readDescriptions()
  const body = Object.entries(descriptions)
    .map(
      ([name, { group, description }]) =>
        `  ${JSON.stringify(name)}: [${JSON.stringify(group)}, ${JSON.stringify(description)}],`
    )
    .join('\n')
  const code = `// Generated by scripts/generate-reference.mjs from the JSDoc beside each value. Do not edit.

/** Each token a theme may set: its group and what it is for. */
export const tokenDescriptions: Record<string, readonly [group: string, description: string]> = {
${body}
}
`
  return format(code, { ...(await resolveConfig(out)), parser: 'typescript' })
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(out, await buildReferenceData())
  const missing = Object.entries(await readDescriptions()).filter(([, d]) => !d.description)
  console.log(`reference.data.ts written; ${missing.length} tokens without a description`)
  for (const [name] of missing) console.log(`  ${name}`)
}
